#!/usr/bin/env python3
"""Gera o adaptador C das mesmas regras Flex da etapa 1, sem modificá-las.

Troca apenas as funções que imprimem JSONL por callbacks que produzem Token.
O arquivo gerado fica versionado para `gcc minic.c` funcionar sem Flex/Python.
"""
import os
import hashlib
from pathlib import Path
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[1]
SPEC = ROOT / 'src/lexer/lexer.l'
OUT = ROOT / 'src/scanner/scanner.c'

CALLBACKS = r'''
#include "../common.h"
static Context *scanner_context;
static void print_token(const char *type, const char *lexeme, size_t len,
                        const char *attr, int has_attr, int line, int col) {
    (void)attr; (void)has_attr;
    Context *ctx=scanner_context;
    if(ctx->count==ctx->capacity) {
        size_t capacity=ctx->capacity ? 2*ctx->capacity : 64;
        Token *tokens=realloc(ctx->tokens,capacity*sizeof(*tokens));
        if(!tokens) { fputs("ERRO ENTRADA: memória insuficiente\n",stderr); exit(2); }
        ctx->tokens=tokens;ctx->capacity=capacity;
    }
    Token token={copy_text(ctx,type,strlen(type)),copy_text(ctx,lexeme,len),line,col,source_position(ctx,line,col),0};
    token.end=token.start+len;
    ctx->tokens[ctx->count++]=token;
}
static void print_int(const char *s,size_t len,int line,int col) { print_token("INT_LIT",s,len,NULL,0,line,col); }
static void print_float(const char *s,size_t len,int line,int col) { print_token("FLOAT_LIT",s,len,NULL,0,line,col); }
static void print_error(const char *type,const char *lexeme,size_t len,int line,int col) {
    (void)lexeme;(void)len;
    Context *ctx=scanner_context;
    if(!ctx->failure) { ctx->stage="LEXICO";ctx->failure=copy_text(ctx,type,strlen(type));ctx->failure_line=line;ctx->failure_column=col; }
}
'''

EPILOGUE = r'''
int scan_source(Context *ctx) {
    scanner_context=ctx;
    current_line=current_column=token_line=token_column=1;
    buffer_reset();
    BEGIN(INITIAL);
    size_t length=ctx->source_length;
    if(length>2147483647U) {
        ctx->stage="ENTRADA";ctx->failure="arquivo excede o limite suportado";
        ctx->failure_line=ctx->failure_column=1;return 0;
    }
    YY_BUFFER_STATE state=yy_scan_bytes(ctx->source,(int)length);
    yylex();
    yy_delete_buffer(state);
    yylex_destroy();
    free(buffer);buffer=NULL;buffer_len=buffer_cap=0;
    scanner_context=NULL;
    return ctx->failure==NULL;
}
'''


def main():
    original = SPEC.read_text(encoding='utf-8')
    first = original.index('static void json_string(')
    last = original.index('static const char *keyword(')
    adapted = original[:first] + CALLBACKS + original[last:]
    adapted = adapted.replace('static FILE *input_file = NULL;', '')
    adapted = adapted[:adapted.rindex('%%')+2] + '\n' + EPILOGUE
    # no POSIX fileno dependency in generated C: the compiler scans strings.
    adapted = '%option never-interactive\n' + adapted
    with tempfile.TemporaryDirectory() as directory:
        spec = Path(directory)/'scanner.l'
        generated = Path(directory)/'scanner.c'
        spec.write_text(adapted,encoding='utf-8')
        subprocess.run(['flex','-o',str(generated),str(spec)],check=True,env=os.environ)
        content=generated.read_text()
        # Stable paths make generation reproducible across checkout locations.
        content=content.replace(str(spec),'src/lexer/lexer.l').replace(str(generated),'src/scanner/scanner.c')
        digest=hashlib.sha256(SPEC.read_bytes().replace(b'\r\n',b'\n')).hexdigest()
        content=f'/* Generated by tools/gerar_scanner.py from src/lexer/lexer.l; SHA256: {digest} */\n'+content
        lines=[]
        for line in content.splitlines():
            indent=line[:len(line)-len(line.lstrip(' \t'))]
            lines.append((indent.expandtabs(4)+line[len(indent):]).rstrip())
        content='\n'.join(lines).rstrip()+'\n'
        OUT.write_text(content,encoding='utf-8')


if __name__=='__main__': main()
